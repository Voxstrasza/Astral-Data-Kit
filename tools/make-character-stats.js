'use strict';

/**
 * Bakes the character base-stat tables into lib/character-stats.js.
 *
 * These two tables are the one thing the Armory needs that the 3.3.5a client does not carry:
 * gtOCTBaseHPByClass and gtOCTBaseMPByClass arrived in Cataclysm, so a Wrath client has no base
 * health, mana or starting stats in it at all. Everything else the Armory reads comes out of the
 * player's own client the way the rest of Astral does.
 *
 * Rather than require a world database for that one fact, the numbers are generated from
 * AzerothCore's own base SQL and checked in. Upstream rather than a live database on purpose: a
 * server with edited stats would otherwise bake its edits in as everyone's default.
 *
 * Usage: node tools/make-character-stats.js ["C:\path\to\AzerothCore"]
 */

const fs = require('fs');
const path = require('path');

const DEFAULT_CORE = 'C:\\Users\\Sean\\Desktop\\AzerothCore';
const OUT = path.join(__dirname, '..', 'lib', 'character-stats.js');

/* Levels past 80 are not modeled. Wrath ends there and every gt* table the Armory reads is
   indexed by level, so a higher cap would be extrapolation dressed up as data. */
const MAX_LEVEL = 80;

/** Pulls the tuples out of a mysqldump INSERT, in the column order the CREATE TABLE declares. */
function valuesOf(sql, table)
{
    const at = sql.indexOf('INSERT INTO `' + table + '` VALUES');

    if (at < 0)
    {
        throw new Error(`no INSERT for ${table}`);
    }

    const body = sql.slice(at, sql.indexOf(';', at));
    const rows = [];

    for (const match of body.matchAll(/\(([-\d,]+)\)/g))
    {
        rows.push(match[1].split(',').map(Number));
    }

    if (!rows.length)
    {
        throw new Error(`${table}: INSERT found but no rows parsed`);
    }

    return rows;
}

function main()
{
    const core = process.argv[2] || DEFAULT_CORE;
    const dir = path.join(core, 'data', 'sql', 'base', 'db_world');

    const classSql = fs.readFileSync(path.join(dir, 'player_class_stats.sql'), 'utf8');
    const raceSql = fs.readFileSync(path.join(dir, 'player_race_stats.sql'), 'utf8');

    /* player_class_stats: Class, Level, BaseHP, BaseMana, Strength, Agility, Stamina, Intellect,
       Spirit. player_race_stats: Race, then the same five stats as signed modifiers. */
    const classRows = valuesOf(classSql, 'player_class_stats').filter((r) => r[1] <= MAX_LEVEL);
    const raceRows = valuesOf(raceSql, 'player_race_stats');

    const byClass = new Map();

    for (const [cls, level, hp, mana, str, agi, sta, int, spi] of classRows)
    {
        if (!byClass.has(cls))
        {
            byClass.set(cls, new Map());
        }

        byClass.get(cls).set(level, [hp, mana, str, agi, sta, int, spi]);
    }

    /* Each class is written as its first level and a dense run from there, so a lookup is an
       index rather than a search. Death knights start at 55 and every other class at 1. */
    const classText = [];

    for (const cls of [...byClass.keys()].sort((a, b) => a - b))
    {
        const levels = byClass.get(cls);
        const from = Math.min(...levels.keys());
        const to = Math.max(...levels.keys());
        const rows = [];

        for (let level = from; level <= to; level++)
        {
            const row = levels.get(level);

            if (!row)
            {
                throw new Error(`class ${cls} has a gap at level ${level}`);
            }

            rows.push(`        [${row.join(', ')}]`);
        }

        classText.push(`    ${cls}: { from: ${from}, rows: [\n${rows.join(',\n')}\n    ] }`);
    }

    const raceText = raceRows
        .map(([race, ...mods]) => `    ${race}: [${mods.join(', ')}]`)
        .join(',\n');

    const out = `'use strict';

/*
 * Character base stats: what a race and class has at a level with nothing equipped.
 *
 * GENERATED by tools/make-character-stats.js from AzerothCore's own base SQL,
 * data/sql/base/db_world/player_class_stats.sql and player_race_stats.sql. Do not hand-edit; run
 * the tool again instead.
 *
 * Baked rather than read from a world database because the 3.3.5a client does not have these
 * numbers: gtOCTBaseHPByClass and gtOCTBaseMPByClass are Cataclysm tables. Everything else the
 * Armory reads still comes from the user's own client. A future patch can let a connected server
 * override these with its own values; today nothing consults the database for them.
 *
 * The two tables combine by addition, which is what AzerothCore's ObjectMgr does when it loads
 * them: a stat is the class row plus the race modifier, and base health and mana are the class's
 * alone with no race component.
 *
 * Base health excludes what stamina contributes. A level 1 warrior reads 20 here and has 60 health
 * in game, the other 40 being GetHealthBonusFromStamina applied to 22 stamina. Base mana is the
 * same shape with intellect.
 */

/** Class -> its first level, then one row per level: BaseHP, BaseMana, str, agi, sta, int, spi. */
const CLASS_STATS = {
${classText.join(',\n')}
};

/** Race -> the five stat modifiers added on top of the class row: str, agi, sta, int, spi. */
const RACE_STATS = {
${raceText}
};

/** Wrath ends at 80 and every level-indexed table the Armory reads stops there too. */
const MAX_LEVEL = ${MAX_LEVEL};

/**
 * What this race and class has at this level, naked.
 *
 * Returns null for a combination that has no row rather than guessing one: a death knight below
 * 55 does not exist, and neither does a level 81 anything.
 */
function baseStats(race, cls, level)
{
    const table = CLASS_STATS[cls];
    const mods = RACE_STATS[race];

    if (!table || !mods || !(level >= table.from) || level > MAX_LEVEL)
    {
        return null;
    }

    const row = table.rows[level - table.from];

    if (!row)
    {
        return null;
    }

    const [baseHealth, baseMana, str, agi, sta, int, spi] = row;

    return {
        baseHealth,
        baseMana,
        str: str + mods[0],
        agi: agi + mods[1],
        sta: sta + mods[2],
        int: int + mods[3],
        spi: spi + mods[4]
    };
}

module.exports = { baseStats, CLASS_STATS, RACE_STATS, MAX_LEVEL };
`;

    fs.writeFileSync(OUT, out);

    const rows = classRows.length;
    const bytes = Buffer.byteLength(out);
    console.log(`lib/character-stats.js written: ${rows} class rows, ${raceRows.length} races, ${(bytes / 1024).toFixed(1)} KB`);
}

main();
